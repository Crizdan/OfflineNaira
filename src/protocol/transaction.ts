import nacl from 'tweetnacl';
import { encodeBase64 } from 'tweetnacl-util';
import { Kobo } from '../domain/money';
import { signBytes, verifySignature, randomNonce, assertDeviceIdMatchesKey } from '../crypto/identity';

export const PROTOCOL_VERSION = 1;

/** The exact fields that are signed. Order matters — this is the wire canonical form. */
export interface UnsignedTransaction {
  txId: string; // UUID v4, generated by sender
  senderDeviceId: string;
  senderPublicKeyB64: string;
  receiverDeviceId: string;
  amountKobo: Kobo;
  createdAt: number; // epoch ms
  expiresAt: number; // epoch ms — offline offers must expire
  nonce: string;
  protocolVersion: number;
}

export interface SignedTransaction extends UnsignedTransaction {
  signatureB64: string;
}

/** Canonical byte serialization used for both signing and verifying. */
function canonicalBytes(tx: UnsignedTransaction): Uint8Array {
  // Deterministic field order, JSON with sorted keys — simple and adequate
  // for a prototype. (A production system would use a fixed binary layout
  // to remove any ambiguity from JSON formatting.)
  const canonical = JSON.stringify({
    amountKobo: tx.amountKobo,
    createdAt: tx.createdAt,
    expiresAt: tx.expiresAt,
    nonce: tx.nonce,
    protocolVersion: tx.protocolVersion,
    receiverDeviceId: tx.receiverDeviceId,
    senderDeviceId: tx.senderDeviceId,
    senderPublicKeyB64: tx.senderPublicKeyB64,
    txId: tx.txId,
  });
  return new TextEncoder().encode(canonical);
}

export function buildUnsignedTransaction(params: {
  txId: string;
  senderDeviceId: string;
  senderPublicKeyB64: string;
  receiverDeviceId: string;
  amountKobo: Kobo;
  ttlMs?: number;
}): UnsignedTransaction {
  const createdAt = Date.now();
  const ttl = params.ttlMs ?? 2 * 60_000; // offline offers expire in 2 minutes by default
  return {
    txId: params.txId,
    senderDeviceId: params.senderDeviceId,
    senderPublicKeyB64: params.senderPublicKeyB64,
    receiverDeviceId: params.receiverDeviceId,
    amountKobo: params.amountKobo,
    createdAt,
    expiresAt: createdAt + ttl,
    nonce: randomNonce(),
    protocolVersion: PROTOCOL_VERSION,
  };
}

export async function signTransaction(tx: UnsignedTransaction): Promise<SignedTransaction> {
  const bytes = canonicalBytes(tx);
  const signatureB64 = await signBytes(bytes);
  return { ...tx, signatureB64 };
}

export interface ValidationResult {
  valid: boolean;
  reason?: string;
}

/**
 * Full validation a receiver must run before ACCEPTED. Never trust that the
 * sender's device claims this is valid — recompute everything locally.
 */
export function validateSignedTransaction(
  tx: SignedTransaction,
  opts: { seenNonces: Set<string>; now?: number },
): ValidationResult {
  const now = opts.now ?? Date.now();

  if (tx.protocolVersion !== PROTOCOL_VERSION) {
    return { valid: false, reason: 'unsupported_protocol_version' };
  }
  if (now > tx.expiresAt) {
    return { valid: false, reason: 'expired' };
  }
  if (tx.amountKobo <= 0) {
    return { valid: false, reason: 'non_positive_amount' };
  }
  if (opts.seenNonces.has(tx.nonce)) {
    return { valid: false, reason: 'replay_detected' };
  }
  // Self-consistency (signature matches the embedded pubkey) is checked
  // below, but that alone doesn't prove the embedded pubkey actually
  // belongs to the claimed senderDeviceId — this does.
  if (!assertDeviceIdMatchesKey(tx.senderDeviceId, tx.senderPublicKeyB64)) {
    return { valid: false, reason: 'device_id_key_mismatch' };
  }
  const { signatureB64, ...unsigned } = tx;
  const bytes = canonicalBytes(unsigned);
  if (!verifySignature(bytes, signatureB64, tx.senderPublicKeyB64)) {
    return { valid: false, reason: 'bad_signature' };
  }
  return { valid: true };
}

/** Receiver's signed acknowledgment, sent back over BLE, itself signed and verifiable. */
export interface SignedReceipt {
  txId: string;
  receiverDeviceId: string;
  receiverPublicKeyB64: string;
  status: 'ACCEPTED' | 'REJECTED';
  reason?: string;
  respondedAt: number;
  signatureB64: string;
}

export async function signReceipt(params: {
  txId: string;
  receiverDeviceId: string;
  receiverPublicKeyB64: string;
  status: 'ACCEPTED' | 'REJECTED';
  reason?: string;
}): Promise<SignedReceipt> {
  const respondedAt = Date.now();
  const payload = {
    txId: params.txId,
    receiverDeviceId: params.receiverDeviceId,
    receiverPublicKeyB64: params.receiverPublicKeyB64,
    status: params.status,
    reason: params.reason ?? null,
    respondedAt,
  };
  const bytes = new TextEncoder().encode(JSON.stringify(payload));
  const signatureB64 = await signBytes(bytes);
  return { ...payload, signatureB64 };
}

export function verifyReceipt(receipt: SignedReceipt): boolean {
  if (!assertDeviceIdMatchesKey(receipt.receiverDeviceId, receipt.receiverPublicKeyB64)) {
    return false;
  }
  const { signatureB64, ...payload } = receipt;
  const bytes = new TextEncoder().encode(JSON.stringify(payload));
  return verifySignature(bytes, signatureB64, receipt.receiverPublicKeyB64);
}

// Re-export for callers that only need a fresh random ID source distinct from crypto nonces.
export function newTxId(): string {
  return encodeBase64(nacl.randomBytes(16)).replace(/[+/=]/g, '').slice(0, 22);
}
